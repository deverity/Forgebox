//! TypeScript export of the contracts (`cargo xtask gen-ts`).
//!
//! Two files are generated under `apps/desktop/src/ipc/`:
//! * `generated.ts`: every DTO, payload and parameter type (specta, deterministic);
//! * `methods.ts`: the method table (name, kind, role, `local_only`, CLI commands), a
//!   typed map `ApiMethods` (params/result/job result/stream item per method), the
//!   notifications, event kinds with their payload types, and the stable error codes.
//!
//! Integers wider than 32 bits (`seq`, byte counts) are exported as `number` on purpose
//! (`specta_typescript::Number` overrides): values stay far below 2^53.

use std::fmt::Write as _;

use specta::Types;

pub use super::common::{API_VERSION, ApiVersion};
use super::common::{ApiError, LaggedDto, Role};
use super::events::{EVENT_PAYLOADS, EventDto, EventFilter, register_payload_types};
use super::fs::FS_ROOTS;
use super::methods::{METHODS, register_method_types};
use crate::transport::TransportKind;
/// Idempotency key of every API operation. Defined in `forge_core::ids` (with the other
/// ULID newtypes) and re-exported here; its `specta::Type` comes from forge-core's
/// `specta` feature.
pub use forge_core::ids::RequestId;

/// Header of every generated file.
pub const TS_HEADER: &str = "// generated by cargo xtask gen-ts — do not edit\n";

/// Paths (relative to the repository root) of the generated files.
pub const GENERATED_TS_PATH: &str = "apps/desktop/src/ipc/generated.ts";
pub const METHODS_TS_PATH: &str = "apps/desktop/src/ipc/methods.ts";

/// All types exported to TypeScript.
pub fn type_collection() -> Types {
    let types = Types::default()
        .register::<ApiVersion>()
        .register::<RequestId>()
        .register::<Role>()
        .register::<ApiError>()
        .register::<LaggedDto>()
        .register::<EventDto>()
        .register::<EventFilter>()
        .register::<TransportKind>();
    let types = register_method_types(types);
    register_payload_types(types)
}

/// Renders the TypeScript types of [`type_collection`] (deterministic: sorted by name).
pub fn export_typescript() -> anyhow::Result<String> {
    let ts = specta_typescript::Typescript::default()
        .export(&type_collection(), specta_serde::Format)
        .map_err(|e| anyhow::anyhow!("specta export failed: {e}"))?;
    Ok(ts)
}

/// Content of `generated.ts`: header + types, LF line endings, one trailing newline.
pub fn generated_ts() -> anyhow::Result<String> {
    let ts = export_typescript()?;
    Ok(format!(
        "{TS_HEADER}{}\n",
        ts.replace("\r\n", "\n").trim_end()
    ))
}

fn ts_string(value: &str) -> String {
    serde_json::to_string(value).expect("strings always serialize")
}

fn ts_opt_string(value: Option<&str>) -> String {
    value.map_or_else(|| "null".to_owned(), ts_string)
}

fn ts_string_list<'a>(values: impl IntoIterator<Item = &'a str>) -> String {
    let items: Vec<String> = values.into_iter().map(ts_string).collect();
    format!("[{}]", items.join(", "))
}

/// Content of `methods.ts`, generated from [`METHODS`].
pub fn methods_ts() -> String {
    let mut out = String::new();
    out.push_str(TS_HEADER);
    out.push_str(
        "// Method table of the Forgebox API (forge_ipc::api::methods::METHODS).\n\
         import type * as T from \"./generated\";\n\n",
    );
    let _ = writeln!(
        out,
        "export const API_VERSION = {{ major: {}, minor: {} }} as const;\n",
        API_VERSION.major, API_VERSION.minor
    );
    out.push_str(
        "export type MethodKind = \"call\" | \"job\" | \"stream\";\n\n\
         export interface MethodMeta {\n\
         \x20 readonly kind: MethodKind;\n\
         \x20 readonly min_role: T.Role;\n\
         \x20 readonly local_only: boolean;\n\
         \x20 readonly long_running: boolean;\n\
         \x20 readonly mutating: boolean;\n\
         \x20 /** `forge` commands served by the method (docs/09). */\n\
         \x20 readonly cli: readonly string[];\n\
         \x20 readonly notification: string | null;\n\
         \x20 readonly lagged_notification: string | null;\n\
         }\n\n",
    );
    out.push_str("export const METHODS = {\n");
    for m in METHODS {
        let cli: Vec<&str> = m
            .cli
            .split(';')
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .collect();
        let _ = writeln!(
            out,
            "  {}: {{ kind: {}, min_role: {}, local_only: {}, long_running: {}, mutating: {}, cli: {}, notification: {}, lagged_notification: {} }},",
            ts_string(m.name),
            ts_string(m.kind.as_str()),
            ts_string(m.min_role.as_str()),
            m.local_only,
            m.long_running,
            m.mutating,
            ts_string_list(cli),
            ts_opt_string(m.notification),
            ts_opt_string(m.lagged_notification),
        );
    }
    out.push_str("} as const satisfies Record<string, MethodMeta>;\n\n");
    out.push_str("export type MethodName = keyof typeof METHODS;\n\n");

    out.push_str(
        "/** Params and result types of every method. */\nexport interface ApiMethods {\n",
    );
    for m in METHODS {
        let mut entry = format!("params: T.{}; result: T.{}", m.params, m.result);
        if let Some(job_result) = m.job_result {
            let _ = write!(entry, "; job_result: T.{job_result}");
        }
        if let Some(item) = m.item {
            let _ = write!(entry, "; item: T.{item}");
        }
        let _ = writeln!(out, "  {}: {{ {entry} }};", ts_string(m.name));
    }
    out.push_str("}\n\n");

    out.push_str("/** Server → client notifications (JSON-RPC without `id`). */\nexport interface ApiNotifications {\n");
    for m in METHODS {
        if let (Some(notification), Some(lagged), Some(item)) =
            (m.notification, m.lagged_notification, m.item)
        {
            let _ = writeln!(out, "  {}: T.{item};", ts_string(notification));
            let _ = writeln!(out, "  {}: T.LaggedDto;", ts_string(lagged));
        }
    }
    out.push_str("}\n\n");

    let kinds: Vec<&str> = EVENT_PAYLOADS.iter().map(|(kind, _)| *kind).collect();
    let _ = writeln!(
        out,
        "export const EVENT_KINDS = {} as const;\nexport type EventKind = (typeof EVENT_KINDS)[number];\n",
        ts_string_list(kinds)
    );
    out.push_str("/** Payload type of each event kind (`EventDto.payload`). */\nexport interface EventPayloads {\n");
    for (kind, payload) in EVENT_PAYLOADS {
        let _ = writeln!(out, "  {}: T.{payload};", ts_string(kind));
    }
    out.push_str("}\n\n");

    let _ = writeln!(
        out,
        "/** Stable error codes (`ApiError.code`); only additions are allowed. */\nexport const ERROR_CODES = {} as const;\nexport type ErrorCode = (typeof ERROR_CODES)[number];\n",
        ts_string_list(forge_core::error::ERROR_CODES.iter().copied())
    );
    let _ = writeln!(
        out,
        "/** First path segments accepted by `fs.*`. */\nexport const FS_ROOTS = {} as const;",
        ts_string_list(FS_ROOTS.iter().copied())
    );
    out
}

/// Every generated file: `(path relative to the repository root, content)`.
pub fn generated_files() -> anyhow::Result<Vec<(&'static str, String)>> {
    Ok(vec![
        (GENERATED_TS_PATH, generated_ts()?),
        (METHODS_TS_PATH, methods_ts()),
    ])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn typescript_contains_contract_types() {
        let ts = export_typescript().unwrap();
        for name in [
            "ApiVersion",
            "RequestId",
            "SiteDto",
            "JobDto",
            "EventEnvelope",
            "JobProgressPayload",
            "ServicePayload",
        ] {
            assert!(
                ts.contains(&format!("export type {name} ")),
                "{name} missing"
            );
        }
        assert!(ts.contains("major: number"), "{ts}");
    }

    #[test]
    fn export_is_deterministic() {
        assert_eq!(export_typescript().unwrap(), export_typescript().unwrap());
        assert_eq!(methods_ts(), methods_ts());
    }

    #[test]
    fn request_id_is_a_ulid_string_on_the_wire() {
        let id = RequestId::new();
        let json = serde_json::to_string(&id).unwrap();
        let text: String = serde_json::from_str(&json).unwrap();
        assert!(text.parse::<ulid::Ulid>().is_ok());
        assert_eq!(serde_json::from_str::<RequestId>(&json).unwrap(), id);
    }

    #[test]
    fn request_id_exports_as_string() {
        let ts = export_typescript().unwrap();
        assert!(ts.contains("export type RequestId = string;"), "{ts}");
    }

    #[test]
    fn every_type_named_in_the_method_table_is_exported() {
        let ts = export_typescript().unwrap();
        let methods = methods_ts();
        for m in METHODS {
            for name in [Some(m.params), Some(m.result), m.job_result, m.item]
                .into_iter()
                .flatten()
            {
                assert!(
                    ts.contains(&format!("export type {name} ")),
                    "{} references {name}, not exported",
                    m.name
                );
            }
            assert!(methods.contains(&format!("\"{}\": {{ kind:", m.name)));
        }
        for (_, payload) in EVENT_PAYLOADS {
            assert!(ts.contains(&format!("export type {payload} ")), "{payload}");
        }
    }

    #[test]
    fn generated_files_use_lf_and_header() {
        for (path, content) in generated_files().unwrap() {
            assert!(content.starts_with(TS_HEADER), "{path}");
            assert!(!content.contains('\r'), "{path}");
            assert!(
                content.ends_with('\n') && !content.ends_with("\n\n"),
                "{path}"
            );
        }
    }
}
