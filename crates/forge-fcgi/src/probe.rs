        assert_eq!(&encoded[5..9], &(300_u32 | 0x8000_0000).to_be_bytes());
        assert!(decode_pairs(&[5, 0, b'a']).is_err(), "truncated");
        assert!(decode_pairs(&[0x80, 0]).is_err(), "truncated 4-byte length");
