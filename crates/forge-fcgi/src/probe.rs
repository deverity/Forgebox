    #[tokio::test]
    async fn failures_are_classified() {
        // Refused: bind, take the port, close.
        let port = {
            let l = std::net::TcpListener::bind("127.0.0.1:0").unwrap();
            l.local_addr().unwrap()
        };
        assert!(!accepts(port, Duration::from_millis(100)).await);
        let err = get_values(port, Duration::from_secs(5)).await.unwrap_err();
        assert!(err.is_connect(), "{err}");
        assert_eq!(ForgeError::from(err).code(), "io");

        // Closed without answering.
        let addr = one_shot(Vec::new()).await;
        let err = get_values(addr, Duration::from_secs(5)).await.unwrap_err();
        assert!(matches!(err, ProbeError::Protocol { .. }), "{err}");

        // Silent peer: timeout.
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let addr = listener.local_addr().unwrap();
        let _keep = tokio::spawn(async move {
            let (_socket, _) = listener.accept().await.unwrap();
            tokio::time::sleep(Duration::from_secs(30)).await;
        });
        let err = get_values(addr, Duration::from_millis(200))
            .await
            .unwrap_err();
        assert!(matches!(err, ProbeError::Timeout { .. }), "{err}");
        assert_eq!(ForgeError::from(err).code(), "timeout");

        // Wrong protocol version.
        let addr = one_shot(vec![2, 10, 0, 0, 0, 0, 0, 0]).await;
        let err = get_values(addr, Duration::from_secs(5)).await.unwrap_err();
        assert!(err.to_string().contains("version 2"), "{err}");
    }

    #[tokio::test]
    async fn health_requires_status_200_and_the_marker() {
        let script = HealthScript::new("C:/F/etc/php/8.3");
        let serve = |body: &'static [u8]| async move {
            let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
            let addr = listener.local_addr().unwrap();
            tokio::spawn(async move {
                // get_values connection
                let (mut socket, _) = listener.accept().await.unwrap();
                read_request(&mut socket).await;
                let mut answer = Vec::new();
                push_record(
                    &mut answer,
                    RecordType::GetValuesResult,
                    0,
                    &encode_pairs([("FCGI_MAX_CONNS", "1")]),
                );
                socket.write_all(&answer).await.unwrap();
                drop(socket);
                // request connection
                let (mut socket, _) = listener.accept().await.unwrap();
                read_request(&mut socket).await;
                let mut answer = Vec::new();
                push_record(&mut answer, RecordType::Stdout, 1, body);
                push_record(&mut answer, RecordType::EndRequest, 1, &[0; 8]);
                socket.write_all(&answer).await.unwrap();
            });
            addr
        };
        let addr =
            serve(b"Content-Type: text/plain\r\n\r\nforgebox-health 8.3.99 cgi-fcgi 77\n").await;
        let report = health(addr, &script, Duration::from_secs(5)).await.unwrap();
        assert_eq!(report.php_version, "8.3.99");
        assert_eq!(report.pid, Some(77));
        assert_eq!(report.values.max_conns, Some(1));

        let addr = serve(b"Status: 404 Not Found\r\n\r\nNo input file specified.").await;
        let err = health(addr, &script, Duration::from_secs(5))
            .await
            .unwrap_err();
        assert!(err.to_string().contains("status 404"), "{err}");
        let addr = serve(b"Content-Type: text/html\r\n\r\n<html>").await;
        let err = health(addr, &script, Duration::from_secs(5))
            .await
            .unwrap_err();
        assert!(err.to_string().contains("unexpected body"), "{err}");
    }

