    /// Accepts one connection and answers `answer` after reading `read` bytes.
    /// Reads a whole request like php-cgi does (closing a socket with unread data resets
    /// it): one management record, or records up to the empty `FCGI_STDIN`.
    async fn read_request(socket: &mut tokio::net::TcpStream) {
        loop {
            let mut header = [0_u8; 8];
            if socket.read_exact(&mut header).await.is_err() {
                return;
            }
            let len = usize::from(u16::from_be_bytes([header[4], header[5]]));
            let mut body = vec![0_u8; len + usize::from(header[6])];
            if socket.read_exact(&mut body).await.is_err() {
                return;
            }
            let kind = header[1];
            if kind == RecordType::GetValues as u8 || (kind == RecordType::Stdin as u8 && len == 0)
            {
                return;
            }
        }
    }

    /// Accepts one connection, reads the request and answers `answer`.
    async fn one_shot(answer: Vec<u8>) -> SocketAddr {
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let addr = listener.local_addr().unwrap();
        tokio::spawn(async move {
            let (mut socket, _) = listener.accept().await.unwrap();
            read_request(&mut socket).await;
            let _ = socket.write_all(&answer).await;
            let _ = socket.shutdown().await;
        });
        addr
    }

