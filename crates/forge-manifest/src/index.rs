//! `index.yaml` of a registry (docs/04 §5): generation and file hashing.
//!
//! [`build_index`] reads `tools/*.yaml` and `stacks/*.yaml`, hashes each file
//! ([`sha256_hex`], over the exact bytes on disk, LF by `.gitattributes`) and resolves the
//! newest stable version offline from `source.releases` ([`latest_version`]). The index is
//! unsigned here; `cargo xtask registry-sign` writes the detached `index.yaml.minisig`.
//! Used by `cargo xtask registry-index`; `lint_registry` checks the same hashes.
//!
//! Blocking file I/O: call from `spawn_blocking` in async code.

use std::path::{Path, PathBuf};

use forge_core::Timestamp;
use sha2::{Digest, Sha256 as Sha256Hasher};

use crate::lint::RegistryDir;
use crate::parse::{self, ManifestError};
use crate::schema::common::{Category, Kind, RegistryKind, Sha256};
use crate::schema::registry::{
    REGISTRY_SCHEMA_VERSION, RegistryEntry, RegistryMetadata, RegistrySpec,
};
use crate::schema::tool::StaticRelease;
use crate::schema::{ApiVersion, Manifest, RegistryManifest, VersionScheme};
use crate::version::Version;
use crate::yaml::YamlError;

/// Header of the generated `index.yaml`.
pub const INDEX_HEADER: &str = "# generated by cargo xtask registry-index — do not edit\n\
# yaml-language-server: $schema=schema/registry.v1.json\n";

/// Lowercase hexadecimal SHA-256 of `bytes`.
pub fn sha256_hex(bytes: &[u8]) -> String {
    use std::fmt::Write as _;
    let digest = Sha256Hasher::digest(bytes);
    let mut out = String::with_capacity(64);
    for byte in digest {
        let _ = write!(out, "{byte:02x}");
    }
    out
}

/// Why an index could not be generated.
#[derive(Debug, thiserror::Error)]
pub enum IndexError {
    #[error("cannot read {path}: {message}")]
    Io { path: PathBuf, message: String },
    #[error("{path}: {source}")]
    Manifest {
        path: PathBuf,
        #[source]
        source: ManifestError,
    },
    #[error("{path}: a {kind} manifest cannot be listed in an index")]
    Misplaced { path: PathBuf, kind: Kind },
    #[error(transparent)]
    Yaml(#[from] YamlError),
}

/// Newest stable (non-prerelease) version among `releases`, by the ordering of `scheme`.
/// Versions that do not parse are ignored (the validator reports them).
pub fn latest_version(scheme: VersionScheme, releases: &[StaticRelease]) -> Option<String> {
    releases
        .iter()
        .filter_map(|r| Version::parse(scheme, &r.version).ok())
        .filter(|v| !v.is_prerelease())
        .max()
        .map(|v| v.as_str().to_owned())
}

/// The entries of `tools/` and `stacks/`, sorted by id.
pub fn build_entries(
    dir: &RegistryDir,
) -> Result<(Vec<RegistryEntry>, Vec<RegistryEntry>), IndexError> {
    let files = dir.manifest_files().map_err(|e| IndexError::Io {
        path: dir.root().to_owned(),
        message: e.to_string(),
    })?;
    let mut tools = Vec::new();
    let mut stacks = Vec::new();
    for path in files {
        let bytes = std::fs::read(&path).map_err(|e| IndexError::Io {
            path: path.clone(),
            message: e.to_string(),
        })?;
        let text = String::from_utf8_lossy(&bytes);
        let manifest = parse::load_str(&text).map_err(|source| IndexError::Manifest {
            path: path.clone(),
            source,
        })?;
        let sha256 = Sha256::new(&sha256_hex(&bytes)).expect("sha256_hex is 64 hex digits");
        let relative = relative_path(&path);
        match &manifest {
            Manifest::Tool(m) => tools.push(RegistryEntry {
                id: m.metadata.id.clone(),
                path: relative,
                sha256,
                categories: categories(m.metadata.category),
                latest: latest_version(m.spec.versioning.scheme, &m.spec.source.releases),
            }),
            Manifest::Extension(m) => tools.push(RegistryEntry {
                id: m.metadata.id.clone(),
                path: relative,
                sha256,
                categories: categories(m.metadata.category),
                latest: latest_version(VersionScheme::Semver, &m.spec.source.releases),
            }),
            Manifest::Stack(m) => stacks.push(RegistryEntry {
                id: m.metadata.id.clone(),
                path: relative,
                sha256,
                categories: Vec::new(),
                latest: None,
            }),
            other => {
                return Err(IndexError::Misplaced {
                    path,
                    kind: other.kind(),
                });
            }
        }
    }
    tools.sort_by(|a, b| a.id.as_str().cmp(b.id.as_str()));
    stacks.sort_by(|a, b| a.id.as_str().cmp(b.id.as_str()));
    Ok((tools, stacks))
}

fn categories(category: Category) -> Vec<Category> {
    vec![category]
}

/// `tools/php.yaml` for a path ending in `tools/php.yaml` (always `/`).
fn relative_path(path: &Path) -> String {
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    let folder = path
        .parent()
        .and_then(Path::file_name)
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    format!("{folder}/{name}")
}

/// Builds the whole index (unsigned: the signature is the detached `index.yaml.minisig`).
pub fn build_index(
    dir: &RegistryDir,
    name: &str,
    url: Option<&str>,
    updated_at: Timestamp,
) -> Result<RegistryManifest, IndexError> {
    let (tools, stacks) = build_entries(dir)?;
    Ok(RegistryManifest {
        api_version: ApiVersion::V1,
        kind: RegistryKind::Registry,
        metadata: RegistryMetadata {
            name: name.to_owned(),
            url: url.map(str::to_owned),
        },
        spec: RegistrySpec {
            schema_version: REGISTRY_SCHEMA_VERSION,
            updated_at,
            tools,
            stacks,
        },
    })
}

/// The text of `index.yaml` for `index` (header + YAML, LF).
pub fn render_index(index: &RegistryManifest) -> Result<String, IndexError> {
    let body = parse::to_yaml(&Manifest::Registry(index.clone())).map_err(|e| match e {
        ManifestError::Yaml(y) => IndexError::Yaml(y),
        other => IndexError::Yaml(YamlError {
            message: other.to_string(),
            location: None,
        }),
    })?;
    Ok(format!("{INDEX_HEADER}{body}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn release(version: &str) -> StaticRelease {
        StaticRelease {
            version: version.to_owned(),
            url: None,
            sha256: None,
            size: None,
            variants: Default::default(),
            published_at: None,
        }
    }

    #[test]
    fn sha256_of_known_input() {
        assert_eq!(
            sha256_hex(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(sha256_hex(b"").len(), 64);
    }

    #[test]
    fn latest_is_the_highest_stable_version() {
        let releases = [
            release("2.4.66"),
            release("2.4.69"),
            release("2.5.0-rc1"),
            release("2.4.9"),
        ];
        assert_eq!(
            latest_version(VersionScheme::Semver, &releases).as_deref(),
            Some("2.4.69")
        );
        assert_eq!(latest_version(VersionScheme::Semver, &[]), None);
        let only_pre = [release("1.0.0-beta1")];
        assert_eq!(latest_version(VersionScheme::Semver, &only_pre), None);
    }

    #[test]
    fn calver_latest_compares_segments_numerically() {
        let releases = [release("2024.9"), release("2024.10")];
        assert_eq!(
            latest_version(VersionScheme::Calver, &releases).as_deref(),
            Some("2024.10")
        );
    }

    #[test]
    fn relative_paths_use_the_folder_name() {
        assert_eq!(
            relative_path(Path::new("/x/registry/tools/php.yaml")),
            "tools/php.yaml"
        );
    }
}
