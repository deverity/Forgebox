//! Managed blocks (ADR-0007, docs/03 §3.1).
//!
//! ```text
//! # forgebox:begin sites (hash=0123456789abcdef)
//! ...rewritten by Forgebox...
//! # forgebox:end sites
//! ```
//!
//! Inside a block Forgebox rewrites; outside it never writes, byte for byte. The hash in
//! the `begin` line is the hash of the body Forgebox wrote last, so an edit made by the
//! user inside the block is detectable ([`crate::drift`]).
//!
//! Everything here is pure text manipulation except [`write_file`], which is blocking
//! file I/O: async callers use `spawn_blocking`.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use forge_core::error::{ForgeError, IoResultExt, Result};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::drift::Drift;

/// Header of files that are 100 % generated (docs/03 §3.1).
pub const GENERATED_HEADER: &str =
    "generated by forgebox — edits will be lost; override via etc/templates/";

/// Comment syntax of the file format being written.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CommentStyle {
    /// `# text` (nginx, apache, caddy, my.ini, postgresql.conf).
    Hash,
    /// `; text` (php.ini: `#` comments are a parse error since PHP 7).
    Semicolon,
    /// Format without comments (mailpit `.args`): no header, no blocks.
    None,
}

impl CommentStyle {
    /// The comment introducer, or `None` for [`CommentStyle::None`].
    pub fn prefix(self) -> Option<char> {
        match self {
            Self::Hash => Some('#'),
            Self::Semicolon => Some(';'),
            Self::None => None,
        }
    }

    fn require_prefix(self) -> Result<char> {
        self.prefix().ok_or_else(|| {
            ForgeError::InvalidInput("this file format does not support managed blocks".to_owned())
        })
    }
}

/// Normalizes text to the output contract: UTF-8 without BOM, LF only, exactly one
/// trailing newline (docs/15 §7). Empty input stays empty.
pub fn normalize_text(text: &str) -> String {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let mut out = text.replace("\r\n", "\n").replace('\r', "\n");
    while out.ends_with("\n\n") {
        out.pop();
    }
    if !out.is_empty() && !out.ends_with('\n') {
        out.push('\n');
    }
    out
}

/// Prefixes `body` with the "generated by forgebox" header in `style`.
pub fn with_generated_header(style: CommentStyle, body: &str) -> String {
    let body = normalize_text(body);
    match style.prefix() {
        Some(c) => format!("{c} {GENERATED_HEADER}\n{body}"),
        None => body,
    }
}

/// Hash (first 16 hex chars of SHA-256) of a block body. CRLF is hashed as LF so an
/// editor that converts line endings does not look like an edit.
pub fn hash_body(body: &str) -> String {
    let normalized = normalize_text(body);
    let digest = Sha256::digest(normalized.as_bytes());
    let mut out = String::with_capacity(16);
    for byte in &digest[..8] {
        let _ = write!(out, "{byte:02x}");
    }
    out
}

fn begin_line(c: char, name: &str, hash: &str) -> String {
    format!("{c} forgebox:begin {name} (hash={hash})")
}

fn end_line(c: char, name: &str) -> String {
    format!("{c} forgebox:end {name}")
}

fn check_name(name: &str) -> Result<()> {
    let ok = !name.is_empty()
        && name
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '_' | '-' | '.'));
    if ok {
        Ok(())
    } else {
        Err(ForgeError::InvalidInput(format!(
            "invalid managed block name '{name}'"
        )))
    }
}

/// Renders a complete block (begin line, body, end line), ending with a newline.
pub fn render_block(style: CommentStyle, name: &str, body: &str) -> Result<String> {
    check_name(name)?;
    let c = style.require_prefix()?;
    let body = normalize_text(body);
    let hash = hash_body(&body);
    Ok(format!(
        "{}\n{body}{}\n",
        begin_line(c, name, &hash),
        end_line(c, name)
    ))
}

/// A block found in a file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParsedBlock {
    /// Block name.
    pub name: String,
    /// Hash recorded in the `begin` line (what Forgebox wrote).
    pub recorded_hash: String,
    /// Hash of the body as it is now.
    pub actual_hash: String,
    /// Current body (LF-normalized).
    pub body: String,
    /// Byte range of the whole block (begin line through end line, including its newline).
    pub range: std::ops::Range<usize>,
}

impl ParsedBlock {
    /// True when the body no longer matches the recorded hash (edited by the user).
    pub fn is_drifted(&self) -> bool {
        self.recorded_hash != self.actual_hash
    }
}

fn parse_begin(line: &str, c: char) -> Option<(String, String)> {
    let rest = line.trim().strip_prefix(c)?.trim_start();
    let rest = rest.strip_prefix("forgebox:begin ")?.trim();
    let (name, tail) = rest.split_once(' ')?;
    let hash = tail
        .trim()
        .strip_prefix("(hash=")?
        .strip_suffix(')')?
        .to_owned();
    Some((name.to_owned(), hash))
}

fn parse_end(line: &str, c: char) -> Option<String> {
    let rest = line.trim().strip_prefix(c)?.trim_start();
    let name = rest.strip_prefix("forgebox:end ")?.trim();
    Some(name.to_owned())
}

/// Finds every managed block in `text`.
///
/// Fails with `config_invalid` when a block is not closed, closed with another name, or
/// when a name appears twice: those files need a human, never a guess.
pub fn parse_blocks(text: &str, style: CommentStyle) -> Result<Vec<ParsedBlock>> {
    let Some(c) = style.prefix() else {
        return Ok(Vec::new());
    };
    let mut blocks: Vec<ParsedBlock> = Vec::new();
    let mut open: Option<(String, String, usize, usize)> = None; // name, hash, start, body_start
    let mut offset = 0usize;
    for line in text.split_inclusive('\n') {
        let line_start = offset;
        offset += line.len();
        match &open {
            None => {
                if let Some((name, hash)) = parse_begin(line, c) {
                    if blocks.iter().any(|b| b.name == name) {
                        return Err(ForgeError::ConfigInvalid(format!(
                            "managed block '{name}' appears twice"
                        )));
                    }
                    open = Some((name, hash, line_start, offset));
                }
            }
            Some((name, _, _, _)) => {
                if let Some(end_name) = parse_end(line, c) {
                    if &end_name != name {
                        return Err(ForgeError::ConfigInvalid(format!(
                            "managed block '{name}' is closed as '{end_name}'"
                        )));
                    }
                    let (name, hash, start, body_start) = open.take().expect("checked above");
                    let body = normalize_text(&text[body_start..line_start]);
                    blocks.push(ParsedBlock {
                        name,
                        recorded_hash: hash,
                        actual_hash: hash_body(&body),
                        body,
                        range: start..offset,
                    });
                } else if parse_begin(line, c).is_some() {
                    return Err(ForgeError::ConfigInvalid(format!(
                        "managed block '{name}' is not closed before the next block"
                    )));
                }
            }
        }
    }
    if let Some((name, ..)) = open {
        return Err(ForgeError::ConfigInvalid(format!(
            "managed block '{name}' is not closed"
        )));
    }
    Ok(blocks)
}

/// What [`upsert_block`] did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum UpsertStatus {
    /// The file did not exist (or was empty): it now holds only the block.
    Created,
    /// The file existed without this block: it was appended.
    Inserted,
    /// The block existed and its body changed.
    Updated,
    /// The block already had exactly this body.
    Unchanged,
    /// The user edited the block and `force` was false: the text is unchanged.
    DriftKept(Drift),
}

/// Result of [`upsert_block`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Upsert {
    /// The new file content. Equal to the input when nothing was written.
    pub text: String,
    /// What happened.
    pub status: UpsertStatus,
}

/// Writes block `name` with `body` into `existing` (the current file content, `None`
/// when the file does not exist) and returns the new content.
///
/// Only the block's own lines change; everything outside is returned byte for byte.
/// A block edited by the user is left alone unless `force` (the UI asks "keep your edit
/// or regenerate", docs/03 §3.1). `file` is only used to label the [`Drift`].
pub fn upsert_block(
    file: &Path,
    existing: Option<&str>,
    style: CommentStyle,
    name: &str,
    body: &str,
    force: bool,
) -> Result<Upsert> {
    let new_block = render_block(style, name, body)?;
    let existing = existing.map(|t| t.strip_prefix('\u{feff}').unwrap_or(t));
    let Some(text) = existing.filter(|t| !t.trim().is_empty()) else {
        return Ok(Upsert {
            text: new_block,
            status: UpsertStatus::Created,
        });
    };
    let blocks = parse_blocks(text, style)?;
    match blocks.iter().find(|b| b.name == name) {
        Some(found) => {
            if found.is_drifted() && !force {
                return Ok(Upsert {
                    text: text.to_owned(),
                    status: UpsertStatus::DriftKept(Drift::new(file, found)),
                });
            }
            if text[found.range.clone()] == new_block {
                return Ok(Upsert {
                    text: text.to_owned(),
                    status: UpsertStatus::Unchanged,
                });
            }
            let mut out = String::with_capacity(text.len() + new_block.len());
            out.push_str(&text[..found.range.start]);
            out.push_str(&new_block);
            out.push_str(&text[found.range.end..]);
            Ok(Upsert {
                text: out,
                status: UpsertStatus::Updated,
            })
        }
        None => {
            let mut out = text.to_owned();
            if !out.ends_with('\n') {
                out.push('\n');
            }
            out.push('\n');
            out.push_str(&new_block);
            Ok(Upsert {
                text: out,
                status: UpsertStatus::Inserted,
            })
        }
    }
}

/// Outcome of a file write.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum WriteOutcome {
    /// File created or content changed.
    Written,
    /// Content already identical; nothing touched.
    Unchanged,
    /// A managed block was edited by the user and kept (see [`UpsertStatus::DriftKept`]).
    DriftKept(Drift),
}

/// Writes `content` atomically (temp file + rename) unless it is identical.
pub fn write_atomic(path: &Path, content: &str) -> Result<WriteOutcome> {
    if let Ok(current) = fs::read(path) {
        if current == content.as_bytes() {
            return Ok(WriteOutcome::Unchanged);
        }
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).at("creating", parent)?;
    }
    let mut tmp_name = path.file_name().unwrap_or_default().to_os_string();
    tmp_name.push(".forgebox-tmp");
    let tmp = path.with_file_name(tmp_name);
    fs::write(&tmp, content.as_bytes()).at("writing", &tmp)?;
    fs::rename(&tmp, path).at("replacing", path)?;
    Ok(WriteOutcome::Written)
}

/// Upserts block `name` into the file at `path` (creating it when missing).
pub fn write_block_file(
    path: &Path,
    style: CommentStyle,
    name: &str,
    body: &str,
    force: bool,
) -> Result<WriteOutcome> {
    let existing = match fs::read(path) {
        Ok(bytes) => Some(String::from_utf8(bytes).map_err(|_| {
            ForgeError::ConfigInvalid(format!("{} is not valid UTF-8", path.display()))
        })?),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(ForgeError::io_at("reading", path, e)),
    };
    let result = upsert_block(path, existing.as_deref(), style, name, body, force)?;
    match result.status {
        UpsertStatus::DriftKept(drift) => Ok(WriteOutcome::DriftKept(drift)),
        UpsertStatus::Unchanged => Ok(WriteOutcome::Unchanged),
        _ => write_atomic(path, &result.text),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use pretty_assertions::assert_eq;

    fn f() -> &'static Path {
        Path::new("etc/nginx/nginx.conf")
    }

    #[test]
    fn normalize_strips_bom_and_crlf() {
        assert_eq!(normalize_text("\u{feff}a\r\nb\r\n\r\n"), "a\nb\n");
        assert_eq!(normalize_text("a"), "a\n");
        assert_eq!(normalize_text(""), "");
    }

    #[test]
    fn creates_file_with_block() {
        let up = upsert_block(f(), None, CommentStyle::Hash, "sites", "a\nb\n", false).unwrap();
        assert_eq!(up.status, UpsertStatus::Created);
        let hash = hash_body("a\nb\n");
        assert_eq!(
            up.text,
            format!("# forgebox:begin sites (hash={hash})\na\nb\n# forgebox:end sites\n")
        );
        assert_eq!(hash.len(), 16);
    }

    #[test]
    fn updates_preserving_text_outside() {
        let first = upsert_block(f(), None, CommentStyle::Hash, "sites", "one\n", false).unwrap();
        let user = format!("# my header\r\n\r\n{}\r\n# my footer", first.text);
        let up = upsert_block(
            f(),
            Some(&user),
            CommentStyle::Hash,
            "sites",
            "two\n",
            false,
        )
        .unwrap();
        assert_eq!(up.status, UpsertStatus::Updated);
        assert!(up.text.starts_with("# my header\r\n\r\n"));
        assert!(up.text.ends_with("\r\n# my footer"));
        assert!(up.text.contains("\ntwo\n"));
        assert!(!up.text.contains("one"));
        // Idempotent.
        let again = upsert_block(
            f(),
            Some(&up.text),
            CommentStyle::Hash,
            "sites",
            "two\n",
            false,
        )
        .unwrap();
        assert_eq!(again.status, UpsertStatus::Unchanged);
        assert_eq!(again.text, up.text);
    }

    #[test]
    fn appends_block_to_user_file() {
        let up = upsert_block(
            f(),
            Some("[mysqld]\nport=3306"),
            CommentStyle::Hash,
            "main",
            "x=1\n",
            false,
        )
        .unwrap();
        assert_eq!(up.status, UpsertStatus::Inserted);
        assert!(
            up.text
                .starts_with("[mysqld]\nport=3306\n\n# forgebox:begin main")
        );
    }

    #[test]
    fn detects_edit_inside_block_and_keeps_it() {
        let first = upsert_block(f(), None, CommentStyle::Hash, "sites", "one\n", false).unwrap();
        let edited = first.text.replace("one", "one edited");
        let blocks = parse_blocks(&edited, CommentStyle::Hash).unwrap();
        assert!(blocks[0].is_drifted());
        let kept = upsert_block(
            f(),
            Some(&edited),
            CommentStyle::Hash,
            "sites",
            "two\n",
            false,
        )
        .unwrap();
        match kept.status {
            UpsertStatus::DriftKept(d) => {
                assert_eq!(d.block, "sites");
                assert_ne!(d.expected_hash, d.actual_hash);
            }
            other => panic!("unexpected {other:?}"),
        }
        assert_eq!(kept.text, edited);
        let forced = upsert_block(
            f(),
            Some(&edited),
            CommentStyle::Hash,
            "sites",
            "two\n",
            true,
        )
        .unwrap();
        assert_eq!(forced.status, UpsertStatus::Updated);
        assert!(forced.text.contains("two") && !forced.text.contains("edited"));
    }

    #[test]
    fn two_blocks_in_one_file_are_independent() {
        let a = upsert_block(f(), None, CommentStyle::Hash, "a", "A\n", false).unwrap();
        let ab = upsert_block(f(), Some(&a.text), CommentStyle::Hash, "b", "B\n", false).unwrap();
        let blocks = parse_blocks(&ab.text, CommentStyle::Hash).unwrap();
        assert_eq!(blocks.len(), 2);
        let a2 = upsert_block(f(), Some(&ab.text), CommentStyle::Hash, "a", "A2\n", false).unwrap();
        let blocks = parse_blocks(&a2.text, CommentStyle::Hash).unwrap();
        assert_eq!(blocks[0].body, "A2\n");
        assert_eq!(blocks[1].body, "B\n");
        assert!(blocks.iter().all(|b| !b.is_drifted()));
    }

    #[test]
    fn semicolon_style_for_ini() {
        let up = upsert_block(f(), None, CommentStyle::Semicolon, "php", "a=1\n", false).unwrap();
        assert!(up.text.starts_with("; forgebox:begin php (hash="));
        assert!(up.text.ends_with("; forgebox:end php\n"));
        assert_eq!(
            parse_blocks(&up.text, CommentStyle::Semicolon)
                .unwrap()
                .len(),
            1
        );
        // A hash-style parser must not see it.
        assert!(
            parse_blocks(&up.text, CommentStyle::Hash)
                .unwrap()
                .is_empty()
        );
    }

    #[test]
    fn broken_structure_is_an_error() {
        let unclosed = "# forgebox:begin a (hash=00)\nx\n";
        assert_eq!(
            parse_blocks(unclosed, CommentStyle::Hash)
                .unwrap_err()
                .code(),
            "config_invalid"
        );
        let wrong = "# forgebox:begin a (hash=00)\n# forgebox:end b\n";
        assert!(parse_blocks(wrong, CommentStyle::Hash).is_err());
        let twice = "# forgebox:begin a (hash=00)\n# forgebox:end a\n# forgebox:begin a (hash=00)\n# forgebox:end a\n";
        assert!(parse_blocks(twice, CommentStyle::Hash).is_err());
    }

    #[test]
    fn crlf_conversion_is_not_a_drift() {
        let first = upsert_block(f(), None, CommentStyle::Hash, "a", "x\ny\n", false).unwrap();
        let crlf = first.text.replace('\n', "\r\n");
        let blocks = parse_blocks(&crlf, CommentStyle::Hash).unwrap();
        assert!(!blocks[0].is_drifted());
    }

    #[test]
    fn rejects_bad_names_and_comment_less_formats() {
        assert!(render_block(CommentStyle::Hash, "bad name", "x").is_err());
        assert!(render_block(CommentStyle::None, "a", "x").is_err());
    }

    #[test]
    fn generated_header_uses_style() {
        assert_eq!(
            with_generated_header(CommentStyle::Hash, "a\n"),
            "# generated by forgebox — edits will be lost; override via etc/templates/\na\n"
        );
        assert!(with_generated_header(CommentStyle::Semicolon, "a").starts_with("; generated"));
        assert_eq!(with_generated_header(CommentStyle::None, "a"), "a\n");
    }

    #[test]
    fn file_roundtrip_preserves_user_text() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("etc").join("my.ini");
        assert_eq!(
            write_block_file(&path, CommentStyle::Hash, "main", "a=1\n", false).unwrap(),
            WriteOutcome::Written
        );
        let mut text = fs::read_to_string(&path).unwrap();
        text.push_str("# user tail\n");
        fs::write(&path, &text).unwrap();
        assert_eq!(
            write_block_file(&path, CommentStyle::Hash, "main", "a=2\n", false).unwrap(),
            WriteOutcome::Written
        );
        let after = fs::read_to_string(&path).unwrap();
        assert!(after.ends_with("# user tail\n") && after.contains("a=2"));
        assert_eq!(
            write_block_file(&path, CommentStyle::Hash, "main", "a=2\n", false).unwrap(),
            WriteOutcome::Unchanged
        );
    }
}
