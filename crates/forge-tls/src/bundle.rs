//! `certs/ca-bundle.pem` (docs/06 §6.5): one PEM file with the local CA and every root
//! the OS trusts ([`forge_core::platform::TrustStore::system_roots`]).
//!
//! Tools with their own TLS stack do not read the Windows store: PHP's OpenSSL and curl
//! (and Composer through them) only trust a CA file. The php.ini overlay points
//! `openssl.cafile` and `curl.cainfo` at this bundle, so a PHP app trusts what the browser
//! trusts: public roots, a corporate TLS inspection root deployed by policy, and the
//! Forgebox CA (`https://api.loja.test` called from `https://loja.test`).
//!
//! The `tls` actor rewrites it at start and whenever the local CA changes; the file only
//! changes when its content does. It holds public certificates only (no key), LF endings.

use std::collections::BTreeSet;
use std::path::Path;

use forge_core::error::Result;
use forge_core::platform::CertThumbprint;

use crate::cert::der_to_pem;

/// Bundle text: `local_ca` first (when there is one), then `system_roots`, without
/// duplicates, each as a `CERTIFICATE` block.
pub fn render(local_ca: Option<&[u8]>, system_roots: &[Vec<u8>]) -> String {
    let mut seen = BTreeSet::new();
    let mut out = String::from(
        "# Forgebox CA bundle: the local CA plus the roots trusted by the OS.\n\
         # Generated by Forgebox (rewritten when they change); do not edit.\n",
    );
    for der in local_ca
        .into_iter()
        .chain(system_roots.iter().map(Vec::as_slice))
    {
        if seen.insert(CertThumbprint::of_der(der)) {
            out.push_str(&der_to_pem(der));
        }
    }
    out
}

/// Writes `text` to `path` unless it already holds exactly that (atomic replace).
/// Returns whether it wrote. Blocking.
pub fn write_if_changed(path: &Path, text: &str) -> Result<bool> {
    if std::fs::read(path).is_ok_and(|existing| existing == text.as_bytes()) {
        return Ok(false);
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)
            .map_err(|e| forge_core::error::ForgeError::io_at("creating", dir, e))?;
    }
    forge_core::paths::write_atomic(path, text.as_bytes())?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn local_ca_first_and_no_duplicates() {
        let (a, b) = (vec![0x30, 0x01, 0xAA], vec![0x30, 0x01, 0xBB]);
        let text = render(Some(&a), &[b.clone(), a.clone(), b.clone()]);
        assert_eq!(text.matches("-----BEGIN CERTIFICATE-----").count(), 2);
        let first = text.find(&der_to_pem(&a)).unwrap();
        let second = text.find(&der_to_pem(&b)).unwrap();
        assert!(first < second);
        assert!(!text.contains('\r'));
        assert_eq!(
            render(None, &[]).matches("BEGIN").count(),
            0,
            "an empty bundle is only the header"
        );
    }

    #[test]
    fn writes_only_on_change() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("certs/ca-bundle.pem");
        assert!(write_if_changed(&path, "x").unwrap());
        assert!(!write_if_changed(&path, "x").unwrap());
        assert!(write_if_changed(&path, "y").unwrap());
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "y");
    }
}
