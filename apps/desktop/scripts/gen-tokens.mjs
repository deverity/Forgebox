// Generates src/design/tokens.css and src/design/tokens.ts from docs/design/tokens.json
// (DTCG, docs/07 sections 2-3). `--check` writes nothing and exits 1 on drift.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
// TOKENS_SOURCE lets tests point at an edited copy to prove the drift check fails.
const sourcePath = process.env.TOKENS_SOURCE ?? resolve(root, "../../docs/design/tokens.json");
const outCss = resolve(root, "src/design/tokens.css");
const outTs = resolve(root, "src/design/tokens.ts");

const HEADER = "GENERATED by scripts/gen-tokens.mjs from docs/design/tokens.json. Do not edit.";

/** Strips `$`-prefixed DTCG metadata and returns `{ name: $value }`. */
function values(group) {
    return Object.fromEntries(
        Object.entries(group)
            .filter(([key]) => !key.startsWith("$"))
            .map(([key, token]) => [key, token.$value]),
    );
}

const num = (value) => Number.parseFloat(value);
const mapValues = (obj, fn) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, fn(v)]));

function stack(families) {
    return families.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
}

function shadowCss(s) {
    return `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`;
}

export function load() {
    const src = JSON.parse(readFileSync(sourcePath, "utf8"));
    const typography = Object.fromEntries(
        Object.entries(src.typography)
            .filter(([key]) => !key.startsWith("$"))
            .map(([name, token]) => {
                const v = token.$value;
                return [
                    name,
                    {
                        fontSize: num(v.fontSize),
                        lineHeight: num(v.lineHeight),
                        fontWeight: v.fontWeight,
                        family: v.fontFamily,
                        letterSpacing: v.letterSpacing ?? "normal",
                        tnum: token.$extensions?.forgebox?.tnum === true,
                    },
                ];
            }),
    );
    return {
        color: {
            light: values(src.color.light),
            dark: values(src.color.dark),
            highContrast: values(src.color["high-contrast"]),
            forced: values(src.color["forced-colors"]),
        },
        font: {
            family: {
                sans: stack(src.font.family.sans.$value),
                mono: stack(src.font.family.mono.$value),
            },
            tnum: src.font.feature.tnum.$value,
        },
        typography,
        space: mapValues(values(src.space), num),
        radius: mapValues(values(src.radius), num),
        shadow: {
            light: mapValues(values(src.shadow.light), shadowCss),
            dark: mapValues(values(src.shadow.dark), shadowCss),
        },
        motion: {
            spring: values(src.motion.spring),
            duration: mapValues(values(src.motion.duration), num),
        },
    };
}

/** Background tokens are emitted as `-solid`; `--bg-canvas/--bg-sidebar` pick solid or transparent. */
function colorVars(set, indent) {
    return Object.entries(set)
        .map(([name, value]) => {
            const prop = name === "bg-canvas" || name === "bg-sidebar" ? `${name}-solid` : name;
            return `${indent}--${prop}: ${value};`;
        })
        .join("\n");
}

function themeBlock(t, selector, mode, indent = "") {
    const out = [`${selector} {`, colorVars(t.color[mode], "  ")];
    for (const [k, v] of Object.entries(t.shadow[mode])) out.push(`  --elevation-${k}: ${v};`);
    out.push(`  color-scheme: ${mode};`, "}");
    const nl = String.fromCharCode(10);
    return out
        .join(nl)
        .split(nl)
        .map((l) => (l ? indent + l : l))
        .join(nl);
}

export function buildCss(t) {
    const L = [];
    L.push(`/* ${HEADER} */`, "");
    L.push("/* Runtime wiring: opaque unless the shell sets data-vibrancy=on. */");
    L.push(":root {");
    L.push(`  --font-feature-tnum: ${t.font.tnum};`);
    for (const [k, v] of Object.entries(t.space)) L.push(`  --space-${k}: ${v}px;`);
    for (const [k, v] of Object.entries(t.motion.duration)) L.push(`  --duration-${k}: ${v}ms;`);
    L.push("  --bg-canvas: var(--bg-canvas-solid);");
    L.push("  --bg-sidebar: var(--bg-sidebar-solid);");
    L.push("}", "");

    L.push("/* Theme: light by default; dark follows the system unless data-theme is set. */");
    L.push(themeBlock(t, ":root", "light"), "");
    L.push("@media (prefers-color-scheme: dark) {");
    L.push(themeBlock(t, ':root:not([data-theme="light"])', "dark", "  "));
    L.push("}", "");
    L.push(themeBlock(t, ':root[data-theme="light"]', "light"), "");
    L.push(themeBlock(t, ':root[data-theme="dark"]', "dark"), "");

    L.push("/* Vibrancy: the OS material shows through only when data-vibrancy=on. */");
    L.push(
        ':root[data-vibrancy="on"] {',
        "  --bg-canvas: transparent;",
        "  --bg-sidebar: transparent;",
        "}",
        "",
    );
    L.push(':root[data-vibrancy="off"] {');
    L.push(
        "  --bg-canvas: var(--bg-canvas-solid);",
        "  --bg-sidebar: var(--bg-sidebar-solid);",
        "}",
        "",
    );

    L.push("/* High contrast: always opaque, regardless of theme and vibrancy. */");
    L.push(':root[data-contrast="high"] {', colorVars(t.color.highContrast, "  "));
    L.push(
        "  --bg-canvas: var(--bg-canvas-solid);",
        "  --bg-sidebar: var(--bg-sidebar-solid);",
        "}",
        "",
    );
    L.push("@media (forced-colors: active) {", "  :root {", colorVars(t.color.forced, "    "));
    L.push(
        "    --bg-canvas: var(--bg-canvas-solid);",
        "    --bg-sidebar: var(--bg-sidebar-solid);",
    );
    L.push("  }", "}", "");

    L.push("/* Tabular numerals for ports, metrics and mono text. */");
    L.push(".tnum {", "  font-feature-settings: var(--font-feature-tnum);", "}", "");

    L.push("/* Tailwind 4: only token-backed colours, sizes, radii and shadows exist. */");
    L.push("@theme {");
    L.push("  --text-*: initial;", "  --radius-*: initial;", "  --spacing: 4px;");
    L.push(`  --font-sans: ${t.font.family.sans};`, `  --font-mono: ${t.font.family.mono};`);
    for (const [name, s] of Object.entries(t.typography)) {
        L.push(`  --text-${name}: ${s.fontSize}px;`);
        L.push(`  --text-${name}--line-height: ${s.lineHeight}px;`);
        L.push(`  --text-${name}--font-weight: ${s.fontWeight};`);
        L.push(`  --text-${name}--letter-spacing: ${s.letterSpacing};`);
    }
    for (const [k, v] of Object.entries(t.radius)) L.push(`  --radius-${k}: ${v}px;`);
    L.push("  --radius-full: 9999px;");
    L.push("}", "");
    L.push("/* Colours and elevation switch at runtime, so they must stay var() references. */");
    L.push("@theme inline {", "  --color-*: initial;", "  --shadow-*: initial;");
    L.push("  --color-transparent: transparent;", "  --color-current: currentcolor;");
    for (const name of Object.keys(t.color.light)) {
        L.push(`  --color-${name.replace(/^bg-/, "")}: var(--${name});`);
    }
    for (const k of Object.keys(t.shadow.light)) L.push(`  --shadow-${k}: var(--elevation-${k});`);
    L.push("}", "");
    return L.join("\n");
}

export function buildTs(t) {
    const json = (v) => JSON.stringify(v, null, 2);
    const colors = { light: t.color.light, dark: t.color.dark, highContrast: t.color.highContrast };
    return `// ${HEADER}

export const colors = ${json(colors)} as const;

export const typography = ${json(t.typography)} as const;

export const fontFamily = ${json(t.font.family)} as const;

export const space = ${json(t.space)} as const;

export const radius = ${json(t.radius)} as const;

export const shadow = ${json(t.shadow)} as const;

export const motion = ${json(t.motion)} as const;

export type ThemeName = keyof typeof colors;
export type ColorToken = keyof (typeof colors)["light"];
export type TypographyToken = keyof typeof typography;
export type SpringToken = keyof (typeof motion)["spring"];
export type DurationToken = keyof (typeof motion)["duration"];
`;
}

function main() {
    const check = process.argv.includes("--check");
    const t = load();
    const outputs = [
        [outCss, buildCss(t)],
        [outTs, buildTs(t)],
    ];
    let drift = false;
    for (const [path, content] of outputs) {
        if (check) {
            const current = existsSync(path)
                ? readFileSync(path, "utf8").replace(/\r\n/g, "\n")
                : null;
            if (current !== content) {
                console.error(`tokens drift: ${path} is out of date; run "pnpm tokens"`);
                drift = true;
            }
        } else {
            mkdirSync(dirname(path), { recursive: true });
            writeFileSync(path, content, "utf8");
            console.log(`wrote ${path}`);
        }
    }
    if (drift) process.exit(1);
    if (check) console.log("tokens up to date");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
