// Fixture of the E2 live suite (M2-E2-T20, scripts/gui-e2e.ps1): a temp portable root with fake
// tools (no downloads), a fixture registry and the free ports the scenarios need.
//
//   node e2e/live/fixture.mjs create [--repo <dir>] [--debug|--release]
//
// prints the context as JSON ({base, root, gui, registry, stallPort, ...}).
//
// What is installed (loose folders under bin/, found by the manifests' `discover` at boot, the
// same way the daemon integration tests do it; the sources are crates/forge-daemon/tests/fixtures):
//   php 8.3.36 + 8.4.27 (fake php.exe / FastCGI php-cgi.exe, ext/ with curl, intl, mbstring, xsl)
//   nginx 1.30.6, mysql 8.4.13 (fake mysqld/mysqladmin), mailpit 1.32.0 (polite)
// The fixture registry is the repo registry minus its signature, plus a `fixture-php` stack
// (everything above, nothing to download) and the tool `fixture-slow`, whose https release URL is
// a local socket that never answers TLS (`stallPort`): an install that can only be cancelled.
// `live_seed` (crates/forge-daemon/examples) marks that registry trusted unsigned in the store.
import { execFileSync } from "node:child_process";
import {
    copyFileSync,
    cpSync,
    existsSync,
    mkdirSync,
    mkdtempSync,
    readFileSync,
    rmSync,
    writeFileSync,
} from "node:fs";
import { createHash } from "node:crypto";
import { createServer } from "node:net";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../../..");

function freePort() {
    return new Promise((ok, fail) => {
        const srv = createServer();
        srv.once("error", fail);
        srv.listen(0, "127.0.0.1", () => {
            const { port } = srv.address();
            srv.close(() => ok(port));
        });
    });
}

function compile(repo, name, out) {
    const src = join(repo, "crates", "forge-daemon", "tests", "fixtures", `${name}.rs`);
    execFileSync("rustc", ["--edition", "2024", "-O", src, "-o", out], { stdio: "pipe" });
}

const sha256 = (text) => createHash("sha256").update(text).digest("hex");

const SLOW_TOOL = (port) => `apiVersion: forgebox.dev/v1
kind: Tool
metadata:
  id: fixture-slow
  name: Fixture Slow
  summary: Live-suite tool whose download never answers
  description: |
    Only exists in the E2 live suite: its https release points at a local socket that never
    completes the TLS handshake, so an install can only be cancelled.
  category: devtool
  tags: [fixture]
  license: MIT
spec:
  platforms: [windows-x64]
  versioning:
    scheme: semver
    channels:
      stable: { constraint: ">=1 <2" }
    series_key: "{major}.{minor}"
  source:
    providers:
      - type: http
        url: "https://127.0.0.1:${port}/fixture-slow-{version}.zip"
    releases:
      - version: "1.0.0"
        url: https://127.0.0.1:${port}/fixture-slow-1.0.0.zip
        sha256: "${"ab".repeat(32)}"
        size: 52428800
  install:
    archive: zip
    strip_root: auto
    layout: versioned
    current_link: true
    path:
      - "."
    size_estimate_mb: 50
`;

const FIXTURE_STACK = `apiVersion: forgebox.dev/v1
kind: Stack
metadata:
  id: fixture-php
  name: Fixture PHP
  summary: "PHP 8.4 + Nginx + MySQL 8.4 + Mailpit (live suite, already installed)"
  description: |
    Stack of the E2 live suite: every tool is already in bin/, nothing is downloaded.
  tags: [php, onboarding]
  order: 0
  icon: php.svg
spec:
  tools:
    - { id: php, series: "8.4" }
    - { id: nginx }
    - { id: mysql, series: "8.4", instance: default }
    - { id: mailpit, instance: default }
  site:
    driver: generic-php
    php: "8.4"
    secure: false
`;

/** Adds an index entry for a manifest text; the index is regenerated by `cargo xtask registry-index`. */
function regenerateIndex(repo, dir) {
    const xtask = join(repo, "target", "debug", "xtask.exe");
    const args = ["registry-index", "--dir", dir, "--name", "official"];
    if (existsSync(xtask)) execFileSync(xtask, args, { stdio: "pipe", cwd: repo });
    else execFileSync("cargo", ["xtask", ...args], { stdio: "pipe", cwd: repo });
}

export async function createLiveRoot({ repo = repoRoot, profile = "debug" } = {}) {
    const base = mkdtempSync(join(tmpdir(), "forgebox-live-"));
    const root = join(base, "root");
    const gui = join(base, "gui");
    const registry = join(base, "registry");
    const fakes = join(base, "fakes");
    for (const d of [join(root, "etc"), join(root, "state"), gui, fakes]) mkdirSync(d, { recursive: true });
    writeFileSync(join(root, "portable.flag"), "");

    const ports = {
        tlsCrl: await freePort(),
        internal: await freePort(),
        databases: await Promise.all(Array.from({ length: 8 }, freePort)),
        web: await Promise.all(Array.from({ length: 4 }, freePort)),
        mail: await Promise.all(Array.from({ length: 4 }, freePort)),
        xdebug: await freePort(),
    };
    const stallPort = await freePort();
    const list = (a) => `[${a.join(", ")}]`;
    writeFileSync(
        join(root, "etc", "forgebox.toml"),
        `[dns]\nenabled = false\n\n[ports.ranges]\ntls-crl = [${ports.tlsCrl}]\ninternal = [${ports.internal}]\n` +
            `databases = ${list(ports.databases)}\nweb = ${list(ports.web)}\nmail = ${list(ports.mail)}\n`,
    );

    // Fake tools.
    const exes = {};
    for (const name of ["fake_php", "fake_nginx", "fake_mysqld", "fake_mailpit"]) {
        exes[name] = join(fakes, `${name}.exe`);
        compile(repo, name, exes[name]);
    }
    const put = (dir, file, exe) => {
        mkdirSync(dir, { recursive: true });
        copyFileSync(exe, join(dir, file));
    };
    for (const version of ["8.3.36", "8.4.27"]) {
        const dir = join(root, "bin", "php", version);
        put(dir, "php.exe", exes.fake_php);
        put(dir, "php-cgi.exe", exes.fake_php);
        mkdirSync(join(dir, "ext"), { recursive: true });
        for (const ext of ["curl", "intl", "mbstring", "xsl"]) writeFileSync(join(dir, "ext", `php_${ext}.dll`), "");
    }
    put(join(root, "bin", "nginx", "1.30.6"), "nginx.exe", exes.fake_nginx);
    const mysql = join(root, "bin", "mysql", "8.4.13", "bin");
    put(mysql, "mysqld.exe", exes.fake_mysqld);
    put(mysql, "mysqladmin.exe", exes.fake_mysqld);
    const mailpit = join(root, "bin", "mailpit", "1.32.0");
    put(mailpit, "mailpit.exe", exes.fake_mailpit);
    writeFileSync(join(mailpit, "fake-mode.txt"), "polite");

    // A project to add as a site.
    const project = join(base, "projects", "loja");
    mkdirSync(project, { recursive: true });
    writeFileSync(join(project, "index.php"), "<?php echo 'ok';\n");

    // Fixture registry.
    cpSync(join(repo, "registry"), registry, { recursive: true });
    rmSync(join(registry, "index.yaml.minisig"), { force: true });
    writeFileSync(join(registry, "tools", "fixture-slow.yaml"), SLOW_TOOL(stallPort));
    writeFileSync(join(registry, "stacks", "fixture-php.yaml"), FIXTURE_STACK);
    regenerateIndex(repo, registry);
    const seed = join(repo, "target", profile, "examples", "live_seed.exe");
    if (!existsSync(seed)) throw new Error(`missing ${seed}: cargo build -p forge-daemon --example live_seed`);
    execFileSync(seed, [root, registry], { stdio: "pipe" });

    return {
        base,
        root,
        gui,
        registry,
        repo,
        project,
        stallPort,
        xdebugPort: ports.xdebug,
        indexSha: sha256(readFileSync(join(registry, "index.yaml"))),
    };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const args = process.argv.slice(2);
    if (args[0] !== "create") {
        console.error("usage: node e2e/live/fixture.mjs create [--repo <dir>] [--release]");
        process.exit(2);
    }
    const at = args.indexOf("--repo");
    const ctx = await createLiveRoot({
        repo: at >= 0 ? resolve(args[at + 1]) : repoRoot,
        profile: args.includes("--release") ? "release" : "debug",
    });
    process.stdout.write(`${JSON.stringify(ctx)}\n`);
}
